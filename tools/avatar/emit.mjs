// Converts the assembled avatar (out/metis-avatar-inner.svgfrag + out/metis-avatar.css) into
// src/components/avatar/MetisAvatarArt.generated.tsx and metis-avatar.generated.css.
// No dependencies. Run `node tools/avatar/assemble.cjs` first (or `npm run avatar:build`).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'out');
const DEST = join(HERE, '..', '..', 'src', 'components', 'avatar');

const fragment = readFileSync(join(OUT, 'metis-avatar-inner.svgfrag'), 'utf8');
const css = readFileSync(join(OUT, 'metis-avatar.css'), 'utf8');

const ALLOWED_TAGS = new Set(['g', 'path', 'ellipse', 'circle', 'rect']);
const ALLOWED_ATTRS = new Set([
  'class',
  'style',
  'd',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'x',
  'y',
  'width',
  'height',
]);

/** Integer coordinates are plenty at the sizes we render; cuts ~25% of the path data. */
const roundPath = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number.parseFloat(n))));
const camel = (prop) => prop.trim().replace(/-([a-z])/g, (_, c) => c.toUpperCase());

function styleObject(style) {
  const entries = style
    .split(';')
    .map((decl) => decl.trim())
    .filter(Boolean)
    .map((decl) => {
      const i = decl.indexOf(':');
      return [camel(decl.slice(0, i)), decl.slice(i + 1).trim()];
    });
  return `{{ ${entries.map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(', ')} }}`;
}

function attrsToJsx(raw) {
  const out = [];
  for (const [, name, value] of raw.matchAll(/([a-z-]+)="([^"]*)"/g)) {
    if (!ALLOWED_ATTRS.has(name)) throw new Error(`Unexpected attribute "${name}"`);
    if (name === 'class') out.push(`className=${JSON.stringify(value)}`);
    else if (name === 'style') out.push(`style=${styleObject(value)}`);
    else if (name === 'd') out.push(`d=${JSON.stringify(roundPath(value))}`);
    else out.push(`${name}=${JSON.stringify(value)}`);
  }
  return out.length ? ` ${out.join(' ')}` : '';
}

// Tokenise the (machine-generated, well-formed) fragment.
const tokens = [...fragment.matchAll(/<(\/?)([a-z]+)([^>]*?)(\/?)>/g)];
const lines = [];
let depth = 2;
for (let i = 0; i < tokens.length; i++) {
  const [, closing, tag, attrs, selfClosing] = tokens[i];
  if (!ALLOWED_TAGS.has(tag)) throw new Error(`Unexpected element <${tag}>`);
  const pad = '  '.repeat(depth);
  if (closing) {
    depth--;
    lines.push(`${'  '.repeat(depth)}</${tag}>`);
    continue;
  }
  const next = tokens[i + 1];
  const isEmpty = selfClosing || (next && next[1] === '/' && next[2] === tag);
  if (isEmpty) {
    lines.push(`${pad}<${tag}${attrsToJsx(attrs)} />`);
    if (!selfClosing) i++; // skip the matching close tag
  } else {
    lines.push(`${pad}<${tag}${attrsToJsx(attrs)}>`);
    depth++;
  }
}
if (depth !== 2) throw new Error('Unbalanced fragment');

const tsx = `// AUTO-GENERATED by tools/avatar/emit.mjs — do not edit by hand.
// Source: tools/avatar/parts.json → assemble.cjs → emit.mjs
import { memo } from 'react';

/** The Metis avatar artwork (all six expressions). Render inside <MetisAvatar>, which sets the expression class. */
export const MetisAvatarArt = memo(function MetisAvatarArt() {
  return (
    <>
${lines.join('\n')}
    </>
  );
});
`;

const cssOut = `/* AUTO-GENERATED by tools/avatar/emit.mjs — do not edit by hand. */
${css}
`;

writeFileSync(join(DEST, 'MetisAvatarArt.generated.tsx'), tsx);
writeFileSync(join(DEST, 'metis-avatar.generated.css'), cssOut);
console.log(`emitted ${lines.length} lines, ${(tsx.length / 1024).toFixed(1)} KB tsx`);
